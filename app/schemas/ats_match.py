from typing import Optional

from pydantic import BaseModel, Field


class ATSMatchResult(BaseModel):
    """
    Structured ATS analysis generated by Groq.
    """

    overall_score: int = Field(
        ge=0,
        le=100,
        description="Overall ATS score",
    )

    skill_score: int = Field(
        ge=0,
        le=100,
        description="Skill matching score",
    )

    experience_score: int = Field(
        ge=0,
        le=100,
        description="Experience matching score",
    )

    education_score: int = Field(
        ge=0,
        le=100,
        description="Education matching score",
    )

    keyword_score: int = Field(
        ge=0,
        le=100,
        description="Keyword matching score",
    )

    certification_score: int = Field(
        ge=0,
        le=100,
        description="Certification matching score",
    )

    matched_skills: list[str] = Field(
        default_factory=list,
        description="Skills present in both resume and job description",
    )

    missing_skills: list[str] = Field(
        default_factory=list,
        description="Important skills missing from the resume",
    )

    strengths: list[str] = Field(
        default_factory=list,
        description="Strong points in the resume",
    )

    weaknesses: list[str] = Field(
        default_factory=list,
        description="Weak points in the resume",
    )

    suggestions: list[str] = Field(
        default_factory=list,
        description="Suggestions to improve ATS score",
    )

    analysis: Optional[str] = Field(
        default="",
        description="Overall ATS analysis",
    )
from datetime import datetime
from typing import Optional

from pydantic import BaseModel


class ATSMatchResponse(BaseModel):

    id: int

    resume_id: int

    job_id: int

    overall_score: int

    skill_score: int

    experience_score: int

    education_score: int

    keyword_score: int

    certification_score: int

    matched_skills: list[str]

    missing_skills: list[str]

    suggestions: list[str]

    analysis: Optional[str]

    created_at: datetime

    class Config:
        from_attributes = True